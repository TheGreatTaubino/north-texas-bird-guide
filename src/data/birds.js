export function isCurrentlySeen(season) {
  const m = new Date().getMonth(); // 0 = Jan, 11 = Dec
  if (season.includes("Year-Round")) return true;
  // April–Sept: months 3–8
  if (season === "April–Sept") return m >= 3 && m <= 8;
  // April–Oct: months 3–9
  if (season === "April–Oct") return m >= 3 && m <= 9;
  // March–Oct: months 2–9
  if (season === "March–Oct") return m >= 2 && m <= 9;
  // March–Nov: months 2–10
  if (season === "March–Nov") return m >= 2 && m <= 10;
  // March–Aug: months 2–7
  if (season === "March–Aug") return m >= 2 && m <= 7;
  // Aug–May: months 7–11, 0–4
  if (season === "Aug–May") return m >= 7 || m <= 4;
  // Oct–April: months 9–11, 0–3
  if (season === "Oct–April") return m >= 9 || m <= 3;
  // Nov–March: months 10–11, 0–2
  if (season === "Nov–March") return m >= 10 || m <= 2;
  // Sept–April: months 8–11, 0–3
  if (season === "Sept–April") return m >= 8 || m <= 3;
  return false;
}
